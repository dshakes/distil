#!/usr/bin/env python3
"""provider_compaction_to_latex.py — turn `distil certify-provider` reports into LaTeX.

Reads every ``report.json`` under ``benchmarks/results/provider-compaction/`` and
emits ``docs/paper/generated/provider_compaction.tex``: one macro per reported
quantity plus the results table body. The provider-compaction paper
(``docs/paper/provider_compaction.tex``) ``\\input``s that fragment, so no number in
the paper is ever hand-typed — the artifacts are the single source of truth.

Run after a certification run:

    python benchmarks/provider_compaction_to_latex.py

Every run directory is keyed by name (``anthropic``, ``anthropic-default-policy``,
...); the key becomes the macro infix, so ``anthropic-default-policy`` yields
``\\pcAnthropicDefaultPolicyAB`` and friends. A run whose ``protocol.json`` hash does
not match the hash embedded in its ``report.json`` is refused rather than published:
that pairing is what makes the pre-registration claim meaningful.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "benchmarks" / "results" / "provider-compaction"
OUT = ROOT / "docs" / "paper" / "generated" / "provider_compaction.tex"

EOL = r" \\"  # LaTeX row terminator (kept out of f-strings: no backslashes allowed there)

# Run directory -> (macro infix, human label for the table, config column).
# Ordered worst-to-best so the table reads as a descent, matching the docs page.
RUNS: list[tuple[str, str, str, str]] = [
    (
        "anthropic-default-policy-replication",
        "AnthropicDefaultTwo",
        r"Anthropic context editing --- \textbf{default}, run 2",
        r"keep=3, trigger 3k",
    ),
    (
        "anthropic-default-policy",
        "AnthropicDefaultOne",
        r"Anthropic context editing --- \textbf{default}, run 1",
        r"keep=3, trigger 3k",
    ),
    (
        "anthropic",
        "AnthropicAggressive",
        r"Anthropic context editing --- aggressive",
        r"keep=0, trigger 500",
    ),
    (
        "openai-threshold-3000",
        "OpenAIThreeK",
        r"OpenAI server-side compaction",
        r"threshold 3k",
    ),
    (
        "openai",
        "OpenAIOneK",
        r"OpenAI server-side compaction",
        r"threshold 1k",
    ),
]


def _pct(x: float) -> str:
    """Render a rate as a percentage the way the reports state it (one decimal)."""
    return f"{100.0 * x:.1f}\\%"


def _macro(name: str, value: str) -> str:
    return "\\newcommand{\\pc" + name + "}{" + value + "}"


def _load(run: str) -> dict:
    d = RESULTS / run
    report = json.loads((d / "report.json").read_text())
    protocol_path = d / "protocol.json"
    if not protocol_path.exists():
        raise SystemExit(f"ERROR: {run} has no protocol.json — refusing to publish it.")
    # The pre-registration claim rests on protocol-before-results. The report embeds
    # the hash of the protocol it ran under; if they disagree, the pairing is broken
    # and the number is not the one that was pre-registered.
    embedded = report.get("protocol_sha256")
    if embedded:
        import hashlib

        # Hash the CANONICAL form, exactly as certify-provider does: sorted keys,
        # indent=2, and no trailing newline (the newline is added when writing the
        # file but is not part of the hashed blob). Hashing raw file bytes here
        # would fail every run for a reason that has nothing to do with the data.
        canonical = json.dumps(
            json.loads(protocol_path.read_text(encoding="utf-8")), sort_keys=True, indent=2
        )
        actual = hashlib.sha256(canonical.encode()).hexdigest()
        if actual != embedded:
            raise SystemExit(
                f"ERROR: {run}: protocol.json hash {actual[:12]} does not match the hash "
                f"{embedded[:12]} embedded in report.json. The pre-registration pairing "
                "is broken; refusing to emit LaTeX."
            )
    return report


def main() -> int:
    if not RESULTS.is_dir():
        print(f"ERROR: no results at {RESULTS}", file=sys.stderr)
        return 1

    lines: list[str] = [
        "% Generated by benchmarks/provider_compaction_to_latex.py — do not edit.",
        "% Source: benchmarks/results/provider-compaction/*/report.json",
        "",
    ]
    rows: list[str] = []

    for run, infix, label, config in RUNS:
        if not (RESULTS / run / "report.json").exists():
            print(f"WARNING: skipping missing run {run}", file=sys.stderr)
            continue
        r = _load(run)
        proto = r.get("protocol", {}) or {}

        ab = _pct(r["ab_change_rate"])
        aa = _pct(r["aa_change_rate"])
        adj = _pct(r["adjusted_change_rate"])
        bound = _pct(r["risk_bound"])
        fired = f"{r['cases_fired']}/{r['cases_total']}"
        cert = "No" if not r.get("certified") else "Yes"

        lines += [
            _macro(infix + "AB", ab),
            _macro(infix + "AA", aa),
            _macro(infix + "Adj", adj),
            _macro(infix + "Bound", bound),
            _macro(infix + "Fired", fired),
            _macro(infix + "Calls", str(r.get("calls_made", ""))),
            _macro(infix + "Model", str(proto.get("model", "")).replace("_", r"\_")),
        ]
        rows.append(f"{label} & {config} & {ab} & {aa} & {adj} & {bound} & {cert}{EOL}")

    # Shared protocol constants — asserted identical across runs so the paper can
    # state them once. A drift here means the runs are not comparable.
    protos = [
        (_load(run).get("protocol", {}) or {})
        for run, _, _, _ in RUNS
        if (RESULTS / run / "report.json").exists()
    ]
    for key, macro in (
        ("n_cases", "N"),
        ("votes", "Votes"),
        ("alpha", "Alpha"),
        ("delta", "Delta"),
    ):
        vals = {p.get(key) for p in protos if key in p}
        if len(vals) == 1:
            lines.append(_macro(macro, str(vals.pop())))
        else:
            print(f"WARNING: {key} differs across runs: {vals}", file=sys.stderr)

    # Cleared-token totals are per-corpus (the 2-round and 7-round episode sets
    # differ), so they are emitted per run rather than pooled into one macro —
    # pooling would print a number that belongs to no experiment.
    for run, infix, _, _ in RUNS:
        if not (RESULTS / run / "report.json").exists():
            continue
        cleared = _load(run).get("total_cleared_input_tokens")
        if cleared:
            lines.append(_macro(infix + "Cleared", f"{cleared:,}"))

    lines += ["", "\\newcommand{\\pcTableBody}{%", *rows, "}"]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
